def quote_for_today():
    """Choose one quote per calendar day, rotating through the local list."""
    day_number = date.today().toordinal()
    return QUOTES[day_number % len(QUOTES)]


def main():
    quote, author = quote_for_today()

    root = tk.Tk()
    root.title("Quote of the Day")
    root.geometry("520x300")
    root.minsize(380, 240)
    root.configure(bg="#f4f1ea")

    style = ttk.Style(root)
    style.theme_use("clam")
    style.configure("Card.TFrame", background="#f4f1ea")
    style.configure("Date.TLabel", background="#f4f1ea", foreground="#766d60", font=("Segoe UI", 10))
    style.configure("Quote.TLabel", background="#f4f1ea", foreground="#24231f", font=("Georgia", 19), wraplength=450, justify="center")
    style.configure("Author.TLabel", background="#f4f1ea", foreground="#5b6755", font=("Segoe UI", 11, "italic"))
    style.configure("Close.TButton", font=("Segoe UI", 10), padding=(14, 7))

    card = ttk.Frame(root, style="Card.TFrame", padding=28)
    card.pack(expand=True, fill="both")
    ttk.Label(card, text="YOUR QUOTE FOR TODAY", style="Date.TLabel").pack(pady=(6, 24))
    ttk.Label(card, text=f'“{quote}”', style="Quote.TLabel").pack(expand=True, pady=4)
    ttk.Label(card, text=f"— {author}", style="Author.TLabel").pack(pady=(14, 20))
    ttk.Button(card, text="Close", command=root.destroy, style="Close.TButton").pack()

    root.mainloop()


if __name__ == "__main__":
    main()
